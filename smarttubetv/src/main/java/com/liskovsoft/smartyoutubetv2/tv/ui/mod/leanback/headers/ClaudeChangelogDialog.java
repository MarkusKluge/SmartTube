import java.util.ArrayList;
import java.util.Date;
import java.util.List;
import java.util.Locale;

/**
 * Claude variant: changelog of this build (newest first, grouped by app version).<br/>
 * Generated by claude-build.sh into the assets: local changes green, upstream white.
 */
final class ClaudeChangelogDialog {
    private static final String ASSET = "claude_changelog.tsv";
    private static final int GREY = Color.parseColor("#9E9E9E");
    private static final int WHITE = Color.parseColor("#E8E8E8");

    private static final class Entry {
        final long timeMs;
        final char kind; // L = local, U = upstream, V = version bump
        final String repo;
        final String hash;
        final String text;

        Entry(long timeMs, char kind, String repo, String hash, String text) {
            this.timeMs = timeMs;
            this.kind = kind;
            this.repo = repo;
            this.hash = hash;
            this.text = text;
        }
    }

    private ClaudeChangelogDialog() {
    }

    static void show(Context context) {
        int green = ContextCompat.getColor(context, R.color.claude_green);

        Dialog dialog = new Dialog(context, android.R.style.Theme_Translucent_NoTitleBar);

        FrameLayout dim = new FrameLayout(context);
        dim.setBackgroundColor(Color.parseColor("#B3000000"));

        LinearLayout panel = new LinearLayout(context);
        panel.setOrientation(LinearLayout.VERTICAL);
        int pad = dp(context, 24);
        panel.setPadding(pad, pad, pad, dp(context, 12));
        GradientDrawable background = new GradientDrawable();
        background.setColor(Color.parseColor("#F2121412"));
        background.setCornerRadius(dp(context, 12));
        background.setStroke(Math.max(1, dp(context, 1)), Color.parseColor("#331B6E2A"));
        panel.setBackground(background);

        TextView title = new TextView(context);
        title.setText("Änderungen");
        title.setTextColor(WHITE);
        title.setTextSize(TypedValue.COMPLEX_UNIT_SP, 22);
        title.setTypeface(Typeface.create("sans-serif-medium", Typeface.BOLD));
        panel.addView(title);

        TextView legend = new TextView(context);
        SpannableStringBuilder legendText = new SpannableStringBuilder();
        append(legendText, "◆ Claude (lokal)", green);
        append(legendText, "     ● Upstream (yuliskov)", WHITE);
        append(legendText, "     neueste zuerst · ▲▼ scrollen · Zurück schließt", GREY);
        legend.setText(legendText);
        legend.setTextSize(TypedValue.COMPLEX_UNIT_SP, 12);
        legend.setPadding(0, dp(context, 4), 0, dp(context, 12));
        panel.addView(legend);

        ScrollView scroll = new ScrollView(context);
        scroll.setFocusable(true);
        scroll.setVerticalScrollBarEnabled(true);
        scroll.setVerticalFadingEdgeEnabled(true);
        scroll.setFadingEdgeLength(dp(context, 24));
        TextView content = new TextView(context);
        content.setText(buildContent(context, green));
        content.setTextColor(WHITE);
        content.setTextSize(TypedValue.COMPLEX_UNIT_SP, 14);
        content.setLineSpacing(dp(context, 3), 1f);
        scroll.addView(content);
        panel.addView(scroll, new LinearLayout.LayoutParams(ViewGroup.LayoutParams.MATCH_PARENT, 0, 1f));

        // Remote: D-pad scrolls a page fraction, no focusable items inside
        scroll.setOnKeyListener((v, keyCode, event) -> {
            if (event.getAction() != KeyEvent.ACTION_DOWN) {
                return false;
            }
            int step = (int) (scroll.getHeight() * 0.4f);
            if (keyCode == KeyEvent.KEYCODE_DPAD_DOWN) {
                scroll.smoothScrollBy(0, step);
                return true;
            } else if (keyCode == KeyEvent.KEYCODE_DPAD_UP) {
                scroll.smoothScrollBy(0, -step);
                return true;
            } else if (keyCode == KeyEvent.KEYCODE_DPAD_LEFT || keyCode == KeyEvent.KEYCODE_DPAD_RIGHT) {
                return true;
            }
            return false;
        });

        FrameLayout.LayoutParams panelParams = new FrameLayout.LayoutParams(
                (int) (context.getResources().getDisplayMetrics().widthPixels * 0.72f),
                (int) (context.getResources().getDisplayMetrics().heightPixels * 0.86f), Gravity.CENTER);
        dim.addView(panel, panelParams);

        dialog.setContentView(dim);
        Window window = dialog.getWindow();
        if (window != null) {
            window.setLayout(ViewGroup.LayoutParams.MATCH_PARENT, ViewGroup.LayoutParams.MATCH_PARENT);
        }
        dialog.setOnShowListener(d -> scroll.requestFocus());
        dialog.show();
    }

    private static CharSequence buildContent(Context context, int green) {
        List<Entry> entries = load(context);
        SpannableStringBuilder text = new SpannableStringBuilder();

        if (entries.isEmpty()) {
            append(text, "Kein Änderungsprotokoll in diesem Build (mit claude-build.sh bauen).", GREY);
            return text;
        }

        SimpleDateFormat dateFormat = new SimpleDateFormat("dd.MM.yy HH:mm", Locale.GERMANY);
        SimpleDateFormat dayFormat = new SimpleDateFormat("dd.MM.yyyy", Locale.GERMANY);
        // Newest first. A version bump is the release of that version: older entries belong to it,
        // everything above the newest bump is newer than the last release (only in this build).
        appendVersionHeader(text, "Nach " + BuildConfig.VERSION_NAME + " · in diesem Build", green, true);

        for (Entry entry : entries) {
            if (entry.kind == 'V') {
                text.append("\n");
                appendVersionHeader(text, "SmartTube " + entry.text + " · veröffentlicht " + dayFormat.format(new Date(entry.timeMs)), WHITE, false);
                continue;
            }

            boolean local = entry.kind == 'L';
            int color = local ? green : WHITE;
            append(text, dateFormat.format(new Date(entry.timeMs)) + "  ", GREY);
            int start = text.length();
            append(text, local ? "◆ " : "● ", local ? green : GREY);
            if ("MSC".equals(entry.repo)) {
                append(text, "[MSC] ", local ? green : GREY);
            }
            append(text, entry.text, color);
            if (local) {
                text.setSpan(new StyleSpan(Typeface.BOLD), start, text.length(), Spanned.SPAN_EXCLUSIVE_EXCLUSIVE);
            }
            int hashStart = text.length();
            append(text, "  " + entry.hash, GREY);
            text.setSpan(new RelativeSizeSpan(0.8f), hashStart, text.length(), Spanned.SPAN_EXCLUSIVE_EXCLUSIVE);
            text.setSpan(new TypefaceSpan("monospace"), hashStart, text.length(), Spanned.SPAN_EXCLUSIVE_EXCLUSIVE);
            text.append("\n");
        }

        return text;
    }

    private static void appendVersionHeader(SpannableStringBuilder text, String header, int color, boolean current) {
        int start = text.length();
        append(text, header + "\n", color);
        text.setSpan(new StyleSpan(Typeface.BOLD), start, text.length(), Spanned.SPAN_EXCLUSIVE_EXCLUSIVE);
        text.setSpan(new RelativeSizeSpan(current ? 1.25f : 1.15f), start, text.length(), Spanned.SPAN_EXCLUSIVE_EXCLUSIVE);
    }

    private static void append(SpannableStringBuilder text, String value, int color) {
        int start = text.length();
        text.append(value);
        text.setSpan(new ForegroundColorSpan(color), start, text.length(), Spanned.SPAN_EXCLUSIVE_EXCLUSIVE);
    }

    private static List<Entry> load(Context context) {
        List<Entry> entries = new ArrayList<>();

        try (BufferedReader reader = new BufferedReader(new InputStreamReader(context.getAssets().open(ASSET), StandardCharsets.UTF_8))) {
            String line;
            while ((line = reader.readLine()) != null) {
                String[] parts = line.split("\t", 5);
                if (parts.length < 5 || parts[1].isEmpty()) {
                    continue;
                }
                try {
                    entries.add(new Entry(Long.parseLong(parts[0]) * 1_000, parts[1].charAt(0), parts[2], parts[3], parts[4]));
                } catch (NumberFormatException e) {
                    // skip
                }
            }
        } catch (IOException e) {
            // no changelog in this build
        }

        return entries;
    }

    private static int dp(Context context, int dp) {
        return Math.round(TypedValue.applyDimension(TypedValue.COMPLEX_UNIT_DIP, dp, context.getResources().getDisplayMetrics()));
    }
}
